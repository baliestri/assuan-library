using System.Globalization;
using System.Text;
using AssuanLibrary.Generators.Models;

namespace AssuanLibrary.Generators.Generation;

internal static class HandlerEmitter {
  internal static string Hint(HandlerModel model)
    => "AssuanHandler_" + Hash(model.Namespace + "." + model.TypeName + "." + model.Method) + ".g.cs";

  internal static string Emit(HandlerModel model) {
    var hash = Hash(model.Namespace + "." + model.TypeName + "." + model.Method);
    var adapter = "__AssuanAdapter_" + hash;
    var field = "__assuan_handler_" + hash;
    var iface = "global::AssuanLibrary.Server.ICommandHandler<" + model.StateType + ">";
    var output = new StringBuilder("// <auto-generated/>\n");
    if (model.Namespace.Length != 0) {
      output.Append("namespace ").Append(model.Namespace).Append(" {\n");
    }

    output.Append(model.Accessibility).Append(model.StaticType ? " static partial class " : " partial class ")
      .Append(model.TypeName).Append(" {\n")
      .Append("  private sealed class ").Append(adapter).Append(" : ").Append(iface).Append(" {\n")
      .Append("    public string Name => ").Append(Quoted(model.Name)).Append(";\n")
      .Append("    public string Description => ").Append(Quoted(model.Description)).Append(";\n")
      .Append("    public global::System.Threading.Tasks.ValueTask HandleAsync(")
      .Append("global::AssuanLibrary.Server.CommandContext<").Append(model.StateType).Append("> context, ")
      .Append("global::System.Threading.CancellationToken token) => ").Append(model.Method)
      .Append("(context, token);\n  }\n")
      .Append("  private static readonly ").Append(iface).Append(' ').Append(field)
      .Append(" = new ").Append(adapter).Append("();\n")
      .Append("  public static ").Append(iface).Append(' ').Append(model.Property)
      .Append(" => ").Append(field).Append(";\n}\n");

    if (model.Namespace.Length != 0) {
      output.Append("}\n");
    }

    return output.ToString();
  }

  private static string Quoted(string text)
    => "\"" + text.Replace("\\", @"\\").Replace("\"", "\\\"").Replace("\t", "\\t") + "\"";

  private static string Hash(string value) {
    unchecked {
      var hash = 14695981039346656037L;
      foreach (var ch in value) {
        hash ^= ch;
        hash *= 1099511628211L;
      }

      return hash.ToString("X16", CultureInfo.InvariantCulture);
    }
  }
}
