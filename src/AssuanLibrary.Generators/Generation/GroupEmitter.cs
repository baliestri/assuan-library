using System.Globalization;
using System.Text;
using AssuanLibrary.Generators.Models;

namespace AssuanLibrary.Generators.Generation;

internal static class GroupEmitter {
  internal static string Hint(GroupModel model)
    => "AssuanGroup_" + Hash(model.Namespace + "." + model.TypeName) + ".g.cs";

  internal static string Emit(GroupModel model) {
    var output = new StringBuilder("// <auto-generated/>\n");
    if (model.Namespace.Length != 0) {
      output.Append("namespace ").Append(model.Namespace).Append(" {\n");
    }

    output.Append(model.Accessibility).Append(model.StaticType ? " static partial class " : " partial class ")
      .Append(model.TypeName).Append(" {\n  public static void RegisterHandlers(")
      .Append("global::AssuanLibrary.Server.CommandRegistry<").Append(model.StateType).Append("> registry) {\n")
      .Append("    if (registry is null) throw new global::System.ArgumentNullException(nameof(registry));\n");
    foreach (var name in model.HandlerProperties) {
      output.Append("    registry.Register(").Append(name).Append(");\n");
    }

    output.Append("  }\n");
    output.Append("  public static void RegisterHandlers(")
      .Append("global::AssuanLibrary.Server.AssuanServer<").Append(model.StateType)
      .Append("> server) {\n")
      .Append("    if (server is null) throw new global::System.ArgumentNullException(nameof(server));\n");
    foreach (var name in model.HandlerProperties) {
      output.Append("    server.Register(").Append(name).Append(");\n");
    }

    output.Append("  }\n");
    if (model.Options.Length != 0) {
      AppendOptionHooks(output, model);
    }

    output.Append("}\n");
    if (model.Namespace.Length != 0) {
      output.Append("}\n");
    }

    return output.ToString();
  }

  private static void AppendOptionHooks(StringBuilder output, GroupModel model) {
    var hooks = "global::AssuanLibrary.Server.ISessionHooks<" + model.StateType + ">";
    var context = "global::AssuanLibrary.Server.CommandContext<" + model.StateType + ">";
    const string CANCELLATION = "global::System.Threading.CancellationToken";
    const string RESULT = "global::System.Threading.Tasks.ValueTask";
    for (var index = 0; index < model.Options.Length; ++index) {
      var bytes = Encoding.ASCII.GetBytes(model.Options[index].Name);
      output.Append("  private static readonly byte[] __assuan_option_").Append(index)
        .Append(" = new byte[] { ");
      for (var byteIndex = 0; byteIndex < bytes.Length; ++byteIndex) {
        if (byteIndex != 0) {
          output.Append(", ");
        }

        output.Append(bytes[byteIndex].ToString(CultureInfo.InvariantCulture));
      }

      output.Append(" };\n");
    }

    output.Append("  public static ").Append(hooks).Append(" CreateHooks(").Append(hooks).Append(" inner) {\n")
      .Append("    if (inner is null) throw new global::System.ArgumentNullException(nameof(inner));\n")
      .Append("    return new __AssuanOptionHooks(inner);\n  }\n")
      .Append("  private sealed class __AssuanOptionHooks : ").Append(hooks).Append(" {\n")
      .Append("    private readonly ").Append(hooks).Append(" _inner;\n")
      .Append("    internal __AssuanOptionHooks(").Append(hooks).Append(" inner) => _inner = inner;\n")
      .Append("    public ").Append(RESULT).Append(" AuthenticateAsync(").Append(context)
      .Append(" context, ").Append(CANCELLATION).Append(" token) => _inner.AuthenticateAsync(context, token);\n")
      .Append("    public ").Append(RESULT).Append(" ResetAsync(").Append(context)
      .Append(" context, ").Append(CANCELLATION).Append(" token) => _inner.ResetAsync(context, token);\n")
      .Append("    public ").Append(RESULT).Append(" ClosedAsync(").Append(model.StateType)
      .Append(" state, global::AssuanLibrary.Server.SessionEnd reason, ").Append(CANCELLATION)
      .Append(" token) => _inner.ClosedAsync(state, reason, token);\n")
      .Append("    public ").Append(RESULT).Append(" OptionAsync(global::AssuanLibrary.Server.OptionRequest request, ")
      .Append(context).Append(" context, ").Append(CANCELLATION).Append(" token) {\n");
    for (var index = 0; index < model.Options.Length; ++index) {
      output.Append("      if (global::System.MemoryExtensions.SequenceEqual<byte>(request.Name.Span, ")
        .Append("new global::System.ReadOnlySpan<byte>(__assuan_option_").Append(index)
        .Append("))) return ").Append(model.Options[index].Method).Append("(request, context, token);\n");
    }

    output.Append("      return _inner.OptionAsync(request, context, token);\n    }\n  }\n");
  }

  private static string Hash(string value) {
    unchecked {
      var hash = 14695981039346656037L;
      foreach (var ch in value) {
        hash ^= ch;
        hash *= 1099511628211L;
      }

      return hash.ToString("X16", CultureInfo.InvariantCulture);
    }
  }
}
